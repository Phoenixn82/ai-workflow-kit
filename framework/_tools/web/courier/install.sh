#!/usr/bin/env bash
# Install the webcred one-way credential courier (spec §3.5). Run as root: `sudo bash courier/install.sh`.
# Idempotent: re-running updates the daemon code and units and keeps the user, the age identity and the store.
#
#   user    webcred (system, no login shell, home /var/lib/webcred 0700)
#   store   /var/lib/webcred/store/ 0700; identity 0600 (generated as webcred); recipient (public key)
#   code    /usr/local/lib/webcred/webcred.py (root-owned: neither webcred nor you can change what runs)
#   units   /etc/systemd/system/webcred.{socket,service}; /run/webcred/sock is group you 0660
#   dep     python-websockets for /usr/bin/python3 (the daemon's CDP client)
set -euo pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
STATE=/var/lib/webcred
LIB=/usr/local/lib/webcred
UNITS=/etc/systemd/system
USER_NAME=webcred
SOCKET_GROUP="${SUDO_USER:?run this with sudo from your own account}"

STAMP=$(date +%Y%m%d-%H%M%S)

die() { echo "install.sh: $*" >&2; exit 2; }
# put MODE SRC DST: install root-owned; an existing DST with different content is kept as DST.bak-webcred-<stamp>.
put() {
    if [[ -e "$3" ]] && ! cmp -s "$2" "$3"; then
        cp -p "$3" "$3.bak-webcred-$STAMP"
        echo "install.sh: backed up $3 -> $3.bak-webcred-$STAMP"
    fi
    install -m "$1" -o root -g root "$2" "$3"
}
[[ $EUID -eq 0 ]] || die "run as root (sudo bash $0)"
command -v age >/dev/null && command -v age-keygen >/dev/null || die "age and age-keygen are required"
getent group "$SOCKET_GROUP" >/dev/null || die "group $SOCKET_GROUP does not exist"

# 1. the daemon's one dependency outside the stdlib
if ! /usr/bin/python3 -c "import websockets.sync.client" 2>/dev/null; then
    pacman -S --needed --noconfirm python-websockets
fi

# 2. the system user and its private home
if ! id "$USER_NAME" >/dev/null 2>&1; then
    useradd --system --user-group --home-dir "$STATE" --no-create-home --shell /usr/bin/nologin "$USER_NAME"
fi
install -d -m 0700 -o "$USER_NAME" -g "$USER_NAME" "$STATE"
install -d -m 0700 -o "$USER_NAME" -g "$USER_NAME" "$STATE/store"
install -d -m 0700 -o "$USER_NAME" -g "$USER_NAME" "$STATE/superseded"   # replaced records, kept 30 days

# 3. the age identity, generated by webcred itself (kept on re-install), and its public recipient
if [[ ! -s "$STATE/identity" ]]; then
    runuser -u "$USER_NAME" -- age-keygen -o "$STATE/identity"
fi
chown "$USER_NAME:$USER_NAME" "$STATE/identity"
chmod 0600 "$STATE/identity"
runuser -u "$USER_NAME" -- sh -c "umask 077; age-keygen -y '$STATE/identity' > '$STATE/recipient.tmp' \
    && mv '$STATE/recipient.tmp' '$STATE/recipient'"

# 4. the daemon code
install -d -m 0755 -o root -g root "$LIB"
put 0644 "$HERE/webcred.py" "$LIB/webcred.py"

# 5. socket activation (the daemon exits after 60 s idle; nothing runs until something connects)
put 0644 "$HERE/webcred.socket" "$UNITS/webcred.socket"
put 0644 "$HERE/webcred.service" "$UNITS/webcred.service"
systemctl daemon-reload
systemctl stop webcred.service 2>/dev/null || true   # the next connection starts the new code
systemctl reset-failed webcred.service 2>/dev/null || true   # a failed earlier start must not block the new code
systemctl enable webcred.socket
systemctl restart webcred.socket
systemctl is-active --quiet webcred.socket || die "webcred.socket is not active after install"
# --lines=0 and `|| true`: status's own exit code (and a pipe into head, under pipefail) must not fail the install.
systemctl --no-pager --lines=0 status webcred.socket || true
